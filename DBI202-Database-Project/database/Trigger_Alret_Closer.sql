CREATE TRIGGER dbo.TRIG_ALERT_CLOSED_REOPEN
ON dbo.SAFETY_ALERT
FOR UPDATE
AS
BEGIN
    DECLARE @OLD_STATUS NVARCHAR(50)
    DECLARE @NEW_STATUS NVARCHAR(50)

    SELECT @OLD_STATUS = DEL.status
    FROM deleted DEL

    SELECT @NEW_STATUS = INS.status
    FROM inserted INS

    IF (@OLD_STATUS = N'CLOSED' AND @NEW_STATUS <> N'CLOSED')
    BEGIN
        PRINT N'ALERT DA CLOSED KHONG DUOC MO LAI'
        ROLLBACK
    END
END
GO