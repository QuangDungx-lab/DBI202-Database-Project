CREATE TABLE dbo.CONTRACTOR (
    ContractorID INT IDENTITY(1,1) CONSTRAINT PK_CONTRACTOR PRIMARY KEY,
    ContractorCode VARCHAR(20) NOT NULL CONSTRAINT UQ_CONTRACTOR_Code UNIQUE,
    ContractorName NVARCHAR(120) NOT NULL,
    ContactEmail VARCHAR(150) NULL,
    IsActive BIT NOT NULL CONSTRAINT DF_CONTRACTOR_Active DEFAULT (1)
);
CREATE TABLE dbo.WORKER (
    WorkerID INT IDENTITY(1,1) CONSTRAINT PK_WORKER PRIMARY KEY,
    ContractorID INT NOT NULL CONSTRAINT FK_WORKER_CONTRACTOR REFERENCES dbo.CONTRACTOR(ContractorID),
    WorkerCode VARCHAR(20) NOT NULL CONSTRAINT UQ_WORKER_Code UNIQUE,
    FullName NVARCHAR(120) NOT NULL,
    JobRole NVARCHAR(80) NOT NULL,
    IsActive BIT NOT NULL CONSTRAINT DF_WORKER_Active DEFAULT (1)
);
CREATE TABLE dbo.CONSTRUCTION_SITE (
    SiteID INT IDENTITY(1,1) CONSTRAINT PK_CONSTRUCTION_SITE PRIMARY KEY,
    SiteCode VARCHAR(20) NOT NULL CONSTRAINT UQ_CONSTRUCTION_SITE_Code UNIQUE,
    SiteName NVARCHAR(150) NOT NULL,
    SiteAddress NVARCHAR(250) NULL,
    IsActive BIT NOT NULL CONSTRAINT DF_CONSTRUCTION_SITE_Active DEFAULT (1)
);
CREATE TABLE dbo.ZONE (
    ZoneID INT IDENTITY(1,1) CONSTRAINT PK_ZONE PRIMARY KEY,
    SiteID INT NOT NULL CONSTRAINT FK_ZONE_SITE REFERENCES dbo.CONSTRUCTION_SITE(SiteID),
    ZoneCode VARCHAR(30) NOT NULL,
    ZoneName NVARCHAR(120) NOT NULL,
    RiskLevel VARCHAR(10) NOT NULL CONSTRAINT CK_ZONE_Risk CHECK (RiskLevel IN ('LOW','MEDIUM','HIGH')),
    CONSTRAINT UQ_ZONE_SiteCode UNIQUE (SiteID, ZoneCode)
);
CREATE TABLE dbo.CAMERA (
    CameraID INT IDENTITY(1,1) CONSTRAINT PK_CAMERA PRIMARY KEY,
    ZoneID INT NOT NULL CONSTRAINT FK_CAMERA_ZONE REFERENCES dbo.ZONE(ZoneID),
    CameraCode VARCHAR(30) NOT NULL CONSTRAINT UQ_CAMERA_Code UNIQUE,
    CameraName NVARCHAR(120) NOT NULL,
    StreamSource NVARCHAR(250) NULL,
    CameraStatus VARCHAR(15) NOT NULL CONSTRAINT DF_CAMERA_Status DEFAULT ('ONLINE') CONSTRAINT CK_CAMERA_Status CHECK (CameraStatus IN ('ONLINE','OFFLINE','MAINTENANCE')),
    LastHeartbeatAt DATETIME2 NULL
);
CREATE TABLE dbo.ASSIGNMENT (
    AssignmentID INT IDENTITY(1,1) CONSTRAINT PK_ASSIGNMENT PRIMARY KEY,
    WorkerID INT NOT NULL CONSTRAINT FK_ASSIGNMENT_WORKER REFERENCES dbo.WORKER(WorkerID),
    ZoneID INT NOT NULL CONSTRAINT FK_ASSIGNMENT_ZONE REFERENCES dbo.ZONE(ZoneID),
    StartDate DATE NOT NULL,
    EndDate DATE NULL,
    CONSTRAINT CK_ASSIGNMENT_Date CHECK (EndDate IS NULL OR EndDate >= StartDate)
);
CREATE TABLE dbo.ATTENDANCE (
    AttendanceID INT IDENTITY(1,1) CONSTRAINT PK_ATTENDANCE PRIMARY KEY,
    WorkerID INT NOT NULL CONSTRAINT FK_ATTENDANCE_WORKER REFERENCES dbo.WORKER(WorkerID),
    SiteID INT NOT NULL CONSTRAINT FK_ATTENDANCE_SITE REFERENCES dbo.CONSTRUCTION_SITE(SiteID),
    CheckInAt DATETIME2 NOT NULL,
    CheckOutAt DATETIME2 NULL,
    CONSTRAINT CK_ATTENDANCE_Time CHECK (CheckOutAt IS NULL OR CheckOutAt >= CheckInAt)
);
CREATE TABLE dbo.SAFETY_CERTIFICATE (
    CertificateID INT IDENTITY(1,1) CONSTRAINT PK_SAFETY_CERTIFICATE PRIMARY KEY,
    WorkerID INT NOT NULL CONSTRAINT FK_CERTIFICATE_WORKER REFERENCES dbo.WORKER(WorkerID),
    CertificateType NVARCHAR(100) NOT NULL,
    IssuedDate DATE NOT NULL,
    ExpiryDate DATE NOT NULL,
    CONSTRAINT CK_CERTIFICATE_Dates CHECK (ExpiryDate > IssuedDate),
    CONSTRAINT UQ_CERTIFICATE_WorkerType UNIQUE (WorkerID, CertificateType)
);
CREATE TABLE dbo.SAFETY_ALERT (
    AlertID INT IDENTITY(1,1) CONSTRAINT PK_SAFETY_ALERT PRIMARY KEY,
    CameraID INT NULL CONSTRAINT FK_ALERT_CAMERA REFERENCES dbo.CAMERA(CameraID),
    ZoneID INT NOT NULL CONSTRAINT FK_ALERT_ZONE REFERENCES dbo.ZONE(ZoneID),
    AlertType VARCHAR(40) NOT NULL,
    Severity VARCHAR(10) NOT NULL CONSTRAINT CK_ALERT_Severity CHECK (Severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    AlertStatus VARCHAR(15) NOT NULL CONSTRAINT DF_ALERT_Status DEFAULT ('OPEN') CONSTRAINT CK_ALERT_Status CHECK (AlertStatus IN ('OPEN','ACKNOWLEDGED','CLOSED')),
    CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_ALERT_CreatedAt DEFAULT (SYSUTCDATETIME()),
    Description NVARCHAR(500) NULL
);
CREATE TABLE dbo.INCIDENT (
    IncidentID INT IDENTITY(1,1) CONSTRAINT PK_INCIDENT PRIMARY KEY,
    AlertID INT NULL CONSTRAINT FK_INCIDENT_ALERT REFERENCES dbo.SAFETY_ALERT(AlertID),
    SiteID INT NOT NULL CONSTRAINT FK_INCIDENT_SITE REFERENCES dbo.CONSTRUCTION_SITE(SiteID),
    IncidentType VARCHAR(60) NOT NULL,
    IncidentStatus VARCHAR(15) NOT NULL CONSTRAINT DF_INCIDENT_Status DEFAULT ('OPEN') CONSTRAINT CK_INCIDENT_Status CHECK (IncidentStatus IN ('OPEN','INVESTIGATING','RESOLVED')),
    OccurredAt DATETIME2 NOT NULL,
    Notes NVARCHAR(1000) NULL
);
CREATE TABLE dbo.AI_METADATA (
    MetadataID BIGINT IDENTITY(1,1) CONSTRAINT PK_AI_METADATA PRIMARY KEY,
    CameraID INT NOT NULL CONSTRAINT FK_AI_METADATA_CAMERA REFERENCES dbo.CAMERA(CameraID),
    EventAt DATETIME2 NOT NULL,
    EventType VARCHAR(40) NOT NULL,
    DetectedLabel VARCHAR(100) NULL,
    Confidence DECIMAL(5,4) NOT NULL CONSTRAINT CK_AI_METADATA_Confidence CHECK (Confidence BETWEEN 0 AND 1),
    ImageReference NVARCHAR(300) NULL,
    SourceMode VARCHAR(10) NOT NULL CONSTRAINT CK_AI_METADATA_Source CHECK (SourceMode IN ('AI','MOCK')),
    InsertedAt DATETIME2 NOT NULL CONSTRAINT DF_AI_METADATA_InsertedAt DEFAULT (SYSUTCDATETIME())
);
CREATE INDEX IX_AI_METADATA_CameraEventAt ON dbo.AI_METADATA(CameraID, EventAt DESC);
CREATE INDEX IX_SAFETY_ALERT_StatusCreated ON dbo.SAFETY_ALERT(AlertStatus, CreatedAt DESC);
CREATE INDEX IX_ATTENDANCE_SiteCheckIn ON dbo.ATTENDANCE(SiteID, CheckInAt DESC);
GO
